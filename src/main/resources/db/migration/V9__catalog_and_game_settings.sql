-- kind: number, text, choice (só as opções listadas) ou computed (calculado pela API)
CREATE TABLE game_fields (
    id       integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    game_id  integer NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    section  text NOT NULL REFERENCES game_sections (key),
    key      text NOT NULL CHECK (key ~ '^[a-z0-9_]+$'),
    label    text NOT NULL,
    kind     text NOT NULL CHECK (kind IN ('number', 'text', 'choice', 'computed')),
    unit     text,
    options  jsonb NOT NULL DEFAULT '[]',
    position integer NOT NULL,
    UNIQUE (game_id, key)
);

